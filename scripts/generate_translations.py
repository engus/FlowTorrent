"""Validate catalogs and emit allocation-free contextual Rust translation tables."""
import argparse
import json
from pathlib import Path
import re

LANGUAGES = ('es', 'pt', 'fr', 'de', 'it', 'pl', 'tr', 'ja', 'ko', 'zh-CN', 'kk', 'uk')
LITERAL = r'"(?:[^"\\]|\\.)*"'
PAIR = re.compile(r'\.text\(\s*(' + LITERAL + r')\s*,\s*(' + LITERAL + r')\s*,?\s*\)')
RU_PAIR = re.compile(r'\bru\s*\?\s*(' + LITERAL + r')\s*:\s*(' + LITERAL + r')')

def validate_catalog(source, catalog, language):
    if set(source) != set(catalog):
        raise ValueError(f'{language}: missing {sorted(set(source)-set(catalog))}, extra {sorted(set(catalog)-set(source))}')
    for key, value in catalog.items():
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f'{language}/{key}: empty translation')
        if any(ord(c) < 32 and c not in '\n\t\r' for c in value):
            raise ValueError(f'{language}/{key}: unsupported control character')
        tokens = lambda s: sorted(re.findall(r'\{[^{}]*\}', s))
        if tokens(value) != tokens(source[key]['en']):
            raise ValueError(f'{language}/{key}: placeholders differ')
        numbers = lambda s: [n.replace(',', '.') for n in re.findall(r'\d+(?:[.,]\d+)?', s)]
        if numbers(source[key]['en']) and numbers(value) != numbers(source[key]['en']):
            raise ValueError(f'{language}/{key}: numeric values differ')

def missing_source_pairs(root, source):
    known = {(v['ru'], v['en']) for v in source.values()}
    actual = set()
    for directory, suffix in [('src', '*.rs'), ('ui', '*.slint')]:
        for path in (root/directory).rglob(suffix):
            content = path.read_text(encoding="utf-8")
            for regex in [PAIR, RU_PAIR] if directory == 'ui' else [PAIR]:
                for match in regex.finditer(content):
                    actual.add(tuple(json.loads(x) for x in match.groups()))
    return sorted(actual-known)

def generate(root):
    source = json.loads((root/'assets/locales/messages.json').read_text(encoding="utf-8"))
    keys = sorted(source, key=lambda key: (source[key]['en'], source[key]['ru']))
    pairs = [(source[k]['en'], source[k]['ru']) for k in keys]
    if len(set(pairs)) != len(pairs):
        raise ValueError('Duplicate contextual source pair')
    catalogs = []
    for language in LANGUAGES:
        catalog = json.loads((root/'assets/locales'/f'{language}.json').read_text(encoding="utf-8"))
        validate_catalog(source, catalog, language)
        catalogs.append(catalog)
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    lines = ['// Generated by scripts/generate_translations.py; edit assets/locales instead.', 'const KEYS: &[(&str, &str)] = &[']
    lines.extend(f'    ({quote(en)}, {quote(ru)}),' for en, ru in pairs)
    lines.extend(['];', 'const VALUES: &[&[&str]] = &['])
    for language, catalog in zip(LANGUAGES, catalogs):
        lines.append(f'    &[ // {language}')
        lines.extend(f'        {quote(catalog[k])},' for k in keys)
        lines.append('    ],')
    lines.extend(['];', '', 'pub(super) fn lookup(language: usize, ru: &str, en: &str) -> Option<&\'static str> {', '    let index = KEYS.binary_search_by(|key| key.0.cmp(en).then_with(|| key.1.cmp(ru))).ok()?;', '    VALUES.get(language)?.get(index).copied()', '}', ''])
    return '\n'.join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    source = json.loads((root/'assets/locales/messages.json').read_text(encoding="utf-8"))
    missing = missing_source_pairs(root, source)
    if missing:
        raise ValueError(f'Uncatalogued source messages: {missing}')
    output = generate(root)
    target = root/'src/ui/translations_generated.rs'
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != output:
            raise ValueError('Generated catalog is stale; run scripts/generate_translations.py')
    else:
        target.write_text(output, encoding="utf-8")
    print(f'{len(source)} contextual messages; {len(LANGUAGES)+2} languages verified')

if __name__ == '__main__':
    main()
